import path from 'node:path'
import {
  applyAdapterEdits,
  fileEdit,
  jsonFileEdit,
  mcpCommand,
  openCodeHome,
  pathExists,
  readTextIfExists,
  writeHookWrapper,
  type AdapterInstallOptions,
  type AdapterUninstallOptions,
  type AgentAdapter,
  type HealthRow,
  type IntegrationChangeSet,
} from '@proofgate/integration-sdk'
import { binaryFound, isRecord, MCP_SERVER_NAME, projectPath } from '../common.js'

export type OpenCodeVersion = 'v1' | 'v2'

function configPath(root: string, scope: 'project' | 'user'): string {
  return scope === 'user' ? path.join(openCodeHome(), 'opencode.json') : projectPath(root, 'opencode.json')
}

function pluginPath(root: string, version: OpenCodeVersion): string {
  return projectPath(root, `.opencode/plugins/proofgate-${version}.ts`)
}

function withOpenCodeMcp(current: Record<string, unknown>, options: AdapterInstallOptions): Record<string, unknown> {
  const command = mcpCommand(options.invoker)
  const mcp = isRecord(current.mcp) ? { ...current.mcp } : {}
  mcp[MCP_SERVER_NAME] = {
    type: 'local',
    command: [command.command, ...command.args],
    enabled: true,
  }
  return { ...current, mcp }
}

function withoutOpenCodeMcp(current: Record<string, unknown>): Record<string, unknown> {
  if (!isRecord(current.mcp)) return current
  const mcp = { ...current.mcp }
  delete mcp[MCP_SERVER_NAME]
  if (Object.keys(mcp).length === 0) {
    const next = { ...current }
    delete next.mcp
    return next
  }
  return { ...current, mcp }
}

function pluginSource(version: OpenCodeVersion, wrapperRelative: string): string {
  const spawnBlock = `
import { spawn } from 'node:child_process'
import path from 'node:path'

function runProofGate(root: string): void {
  const wrapper = path.join(root, ${JSON.stringify(wrapperRelative.replace(/\\/g, '/'))})
  const child = spawn(process.execPath, [wrapper], {
    cwd: root,
    detached: true,
    stdio: 'ignore',
    env: { ...process.env, PROOFGATE_INTEGRATION_HOOK: 'opencode' },
  })
  child.unref()
}
`
  if (version === 'v1') {
    return `// Generated by ProofGate for OpenCode v1. Reinstall after upgrading OpenCode.
${spawnBlock}
export const ProofGate = async (input?: { directory?: string }) => {
  const root = input?.directory ?? process.cwd()
  return {
    event: async ({ event }: { event: { type?: string } }) => {
      if (event?.type === 'session.idle') runProofGate(root)
    },
  }
}
`
  }
  return `// Generated by ProofGate for OpenCode v2 (Plugin.define). Reinstall after upgrading OpenCode.
import { Plugin } from '@opencode-ai/plugin'
${spawnBlock}
export default Plugin.define({
  name: 'proofgate',
  async setup(ctx: { directory?: string; event: { subscribe: (name: string, handler: () => void) => void } }) {
    const root = ctx.directory ?? process.cwd()
    ctx.event.subscribe('session.idle', () => runProofGate(root))
  },
})
`
}

export function createOpenCodeAdapter(version: OpenCodeVersion): AgentAdapter {
  const id = version === 'v1' ? 'opencode-v1' : 'opencode-v2'
  return {
    id,
    displayName: version === 'v1' ? 'OpenCode v1' : 'OpenCode v2',
    description: version === 'v1'
      ? 'Local MCP server and a session.idle plugin for OpenCode v1.'
      : 'Local MCP server and a Plugin.define integration for OpenCode v2.',
    capabilities: {
      manualVerification: true,
      mcpVerification: true,
      automaticCompletionChecks: true,
      automaticFileChangeEvents: false,
      blockingFeedback: false,
      limitations: [
        'The generated plugin targets the documented session.idle event. Reinstall after an OpenCode major upgrade.',
        'Plugin execution runs asynchronously; it reports completion evidence but does not block the agent turn.',
      ],
    },

    async detect(root) {
      const binFound = binaryFound('opencode', root)
      const projectConfig = await pathExists(configPath(root, 'project'))
      const userConfig = await pathExists(configPath(root, 'user'))
      return {
        installed: binFound || projectConfig || userConfig,
        binFound,
        configFound: projectConfig || userConfig,
        ...(projectConfig ? { configScope: 'project' as const } : userConfig ? { configScope: 'user' as const } : {}),
      }
    },

    async install(options): Promise<IntegrationChangeSet> {
      const edits = []
      if (options.includeMcp) {
        edits.push(
          await jsonFileEdit(
            configPath(options.root, options.scope),
            (current) => withOpenCodeMcp(current, options),
            'register local MCP server',
          ),
        )
      }
      if (options.includeHooks) {
        const wrapper = await writeHookWrapper({
          root: options.root,
          name: `opencode-${version}`,
          invoker: options.invoker,
          provider: 'opencode',
          extraArgs: ['--quiet'],
        })
        const wrapperRelative = path.relative(options.root, wrapper.path).replace(/\\/g, '/')
        const plugin = pluginPath(options.root, version)
        const before = await readTextIfExists(plugin)
        edits.push(fileEdit(plugin, before, pluginSource(version, wrapperRelative), 'install OpenCode plugin'))
      }
      return applyAdapterEdits({
        root: options.root,
        adapterId: id,
        scope: options.scope,
        edits,
        dryRun: options.dryRun,
        notes: [
          'Restart OpenCode after installing so it loads the plugin and MCP configuration.',
          'MCP server name: proofgate',
        ],
      })
    },

    async uninstall(options: AdapterUninstallOptions): Promise<IntegrationChangeSet> {
      const edits = []
      const config = configPath(options.root, options.scope)
      if (await pathExists(config)) {
        edits.push(await jsonFileEdit(config, withoutOpenCodeMcp, 'remove MCP server'))
      }
      const plugin = pluginPath(options.root, version)
      const before = await readTextIfExists(plugin)
      if (before !== null) edits.push(fileEdit(plugin, before, null, 'remove OpenCode plugin'))
      return applyAdapterEdits({
        root: options.root,
        adapterId: id,
        scope: options.scope,
        edits,
        dryRun: options.dryRun,
        backup: false,
      })
    },

    async health(options): Promise<HealthRow[]> {
      const rows: HealthRow[] = []
      const config = await readTextIfExists(configPath(options.root, options.scope))
      rows.push(
        config?.includes(`"${MCP_SERVER_NAME}"`)
          ? { level: 'ok', message: 'MCP server is registered.' }
          : { level: 'warn', message: 'MCP server is not registered.' },
      )
      if (options.includeHooks) {
        rows.push(
          (await pathExists(pluginPath(options.root, version)))
            ? { level: 'ok', message: `OpenCode ${version} plugin exists.` }
            : { level: 'warn', message: `OpenCode ${version} plugin is missing.` },
        )
      }
      return rows
    },
  }
}

export const openCodeV1Adapter = createOpenCodeAdapter('v1')
export const openCodeV2Adapter = createOpenCodeAdapter('v2')
